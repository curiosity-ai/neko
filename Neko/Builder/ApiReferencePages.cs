        // ------------------------------------------------------------------ model

        private sealed class Doc
        {
            public XElement? Summary, Remarks, Returns, Value, Example;
            public readonly Dictionary<string, XElement> Params = new();
            public readonly Dictionary<string, XElement> TypeParams = new();
            public readonly List<(string Cref, XElement Text)> Exceptions = new();
        }

        private sealed class Param
        {
            public string Type = "", Name = "", Modifier = "";
        }

        private sealed class Member
        {
            public Kind Kind;
            public string Name = "", ReturnType = "", Signature = "", Title = "", Anchor = "", SourceFile = "";
            public int Line;
            public List<string> TypeParams = new();
            public List<Param> Params = new();
            public Doc Doc = new();
        }

        private sealed class TypeModel
        {
            public string Name = "", Kind = "class", Namespace = "", Declaration = "", SourceFile = "";
            public int Line;
            public List<string> TypeParams = new();
            public List<string> Bases = new();
            public bool IsStatic, IsSealed;
            public Doc Doc = new();
            public List<Member> Members = new();
            public List<(string Name, string Value, Doc Doc)> EnumValues = new();
        }

        private sealed class Page
        {
            public string Path = "";             // the type page
            public string OutputDir = "";        // where member pages go
            public Dictionary<string, string> Attrs = new(StringComparer.OrdinalIgnoreCase);
            public TypeModel? Model;
        }

        // Pages written in a run: path → content, so links can be resolved before anything is written.
        private sealed class Context
        {
            public string InputDir = "";
            public string CurrentType = "";                                                       // the type whose pages are being rendered
            public readonly Dictionary<string, string> TypePages = new(StringComparer.Ordinal);   // type name → type page path
            public readonly Dictionary<string, string> MemberPages = new(StringComparer.Ordinal); // "Type.Member" → member page path
        }

        // ------------------------------------------------------------------ entry point

        internal static void Run(
            string inputDir,
            IReadOnlyList<string> markdownFiles,
            Func<string, string?> resolveRoot,
            Action<string, string> reportMissingRoot,
            ApiDocsSync.Result result,
            bool verbose,
            bool dryRun)
        {
            var ctx = new Context { InputDir = inputDir };
            var pages = new List<Page>();

            foreach (var mdPath in markdownFiles)
            {
                var text = File.ReadAllText(mdPath);
                var m = TypeMarker.Match(text);
                while (m.Success && ApiDocsSync.InsideFence(text, m.Index)) m = m.NextMatch();
                if (!m.Success) continue;

                var page = new Page { Path = mdPath, Attrs = ApiDocsSync.ParseAttrs(m.Groups["attrs"].Value) };
                var rel = Path.GetRelativePath(inputDir, mdPath);
                page.Attrs.TryGetValue("repo", out var repo);
                page.Attrs.TryGetValue("file", out var files);
                page.Attrs.TryGetValue("type", out var typeName);
                if (string.IsNullOrEmpty(repo) || string.IsNullOrEmpty(files) || string.IsNullOrEmpty(typeName))
                {
                    Console.WriteLine($"  api-docs: malformed api:type marker in {rel} (needs repo=, file= and type=).");
                    result.Errors++;
                    continue;
                }

                var root = resolveRoot(repo);
                if (root is null)
                {
                    reportMissingRoot(repo, rel);
                    continue;
                }

                var sources = new List<(string Rel, string Text)>();
                var missing = false;
                foreach (var f in files.Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
                {
                    var full = Path.Combine(root, f.Replace('\\', '/'));
                    if (!File.Exists(full))
                    {
                        Console.WriteLine($"  api-docs: source file not found ({f}) — leaving {rel} as-is.");
                        missing = true;
                        break;
                    }
                    sources.Add((f.Replace('\\', '/'), File.ReadAllText(full)));
                }
                if (missing) { result.Skipped++; continue; }

                page.Model = BuildModel(typeName, sources);
                if (page.Model is null)
                {
                    Console.WriteLine($"  api-docs: type '{typeName}' not found in {files} — leaving {rel} as-is.");
                    result.Errors++;
                    continue;
                }

                var dir = Path.GetDirectoryName(mdPath)!;
                var stem = Path.GetFileNameWithoutExtension(mdPath);
                page.OutputDir = IsFolderIndex(stem) ? dir : Path.Combine(dir, stem);
                pages.Add(page);
            }

            // Every type and member page is known before any page is rendered, so a <see cref>
            // to another documented type or member resolves to a relative link.
            foreach (var page in pages)
            {
                ctx.TypePages[page.Model!.Name] = page.Path;
                foreach (var group in page.Model.Members.GroupBy(m => (m.Kind, m.Name)))
                    ctx.MemberPages[$"{page.Model.Name}.{group.Key.Name}"] = MemberPagePath(page, group.Key.Kind, group.Key.Name);
            }

            foreach (var page in pages)
                WritePage(ctx, page, result, verbose, dryRun);
        }

        private static bool IsFolderIndex(string stem) =>
            stem.Equals("index", StringComparison.OrdinalIgnoreCase) || stem.Equals("readme", StringComparison.OrdinalIgnoreCase);

        private static string MemberPagePath(Page page, Kind kind, string name) => kind == Kind.Constructor
            ? Path.Combine(page.OutputDir, "constructors.md")
            : Path.Combine(page.OutputDir, Sections.First(s => s.Kind == kind).Folder, Kebab(name) + ".md");

        // ------------------------------------------------------------------ model building

        private static TypeModel? BuildModel(string typeName, List<(string Rel, string Text)> sources)
        {
            var parts = new List<(BaseTypeDeclarationSyntax Decl, string Rel)>();
            foreach (var (rel, text) in sources)
            {
                var root = CSharpSyntaxTree.ParseText(text).GetCompilationUnitRoot();
                parts.AddRange(root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>()
                    .Where(t => t.Parent is not BaseTypeDeclarationSyntax && t.Identifier.Text == typeName)
                    .Select(t => (t, rel)));
            }
            if (parts.Count == 0) return null;

            var first = parts.FirstOrDefault(p => GetDocTrivia(p.Decl) is not null);
            if (first.Decl is null) first = parts[0];

            var model = new TypeModel
            {
                Name = typeName,
                Namespace = GetNamespace(parts[0].Decl),
                Doc = ParseDoc(first.Decl),
                SourceFile = first.Rel,
                Line = LineOf(first.Decl),
            };

            var modifiers = parts.SelectMany(p => p.Decl.Modifiers).Select(t => t.Text).ToHashSet();
            model.IsStatic = modifiers.Contains("static");
            model.IsSealed = modifiers.Contains("sealed");

            foreach (var (decl, rel) in parts)
            {
                if (decl is TypeDeclarationSyntax td && td.TypeParameterList is not null && model.TypeParams.Count == 0)
                    model.TypeParams = td.TypeParameterList.Parameters.Select(p => p.Identifier.Text).ToList();
                if (decl.BaseList is not null)
                    foreach (var b in decl.BaseList.Types)
                    {
                        var name = Collapse(b.Type.ToString());
                        if (!model.Bases.Contains(name)) model.Bases.Add(name);
                    }
            }

            model.Kind = parts[0].Decl switch
            {
                InterfaceDeclarationSyntax => "interface",
                StructDeclarationSyntax => "struct",
                EnumDeclarationSyntax => "enum",
                RecordDeclarationSyntax r => r.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) ? "record struct" : "record",
                _ => "class",
            };

            var keep = new[] { "public", "protected", "internal", "static", "abstract", "sealed", "readonly" };
            var mods = keep.Where(modifiers.Contains).ToList();
            model.Declaration = string.Join(" ", mods.Append(model.Kind)) + " " + typeName +
                                (model.TypeParams.Count > 0 ? "<" + string.Join(", ", model.TypeParams) + ">" : "") +
                                (model.Bases.Count > 0 ? " : " + string.Join(", ", model.Bases) : "");

            var inInterface = model.Kind == "interface";
            foreach (var (decl, rel) in parts)
            {
                if (decl is EnumDeclarationSyntax en)
                {
                    foreach (var v in en.Members)
                        model.EnumValues.Add((v.Identifier.Text, v.EqualsValue?.Value.ToString() ?? "", ParseDoc(v)));
                    continue;
                }

                foreach (var node in ((TypeDeclarationSyntax)decl).Members)
                {
                    if (!inInterface && !IsVisible(node.Modifiers)) continue;
                    var member = ToMember(node, typeName);
                    if (member is null) continue;
                    member.SourceFile = rel;
                    member.Line = LineOf(node);
                    model.Members.Add(member);
                }
            }

            // Learn's overload anchor: the member name followed by its parameter types.
            foreach (var group in model.Members.GroupBy(m => (m.Kind, m.Name)))
            {
                var used = new HashSet<string>();
                foreach (var m in group)
                {
                    var anchor = Kebab(m.Name) + string.Concat(m.Params.Select(p => "-" + Regex.Replace(ShortType(p.Type).ToLowerInvariant(), "[^a-z0-9]+", "")));
                    if (m.TypeParams.Count > 0) anchor = Kebab(m.Name) + "-" + string.Join("-", m.TypeParams.Select(t => t.ToLowerInvariant())) + anchor.Substring(Kebab(m.Name).Length);
                    var unique = anchor;
                    for (var i = 2; !used.Add(unique); i++) unique = anchor + "-" + i;
                    m.Anchor = unique;
                }
            }
            return model;
        }

        private static Member? ToMember(MemberDeclarationSyntax node, string typeName)
        {
            var mods = string.Join(" ", node.Modifiers.Select(t => t.Text).Where(t => t != "async" && t != "partial" && t != "extern" && t != "unsafe"));
            string Prefix(string rest) => (mods.Length > 0 ? mods + " " : "") + rest;

            switch (node)
            {
                case MethodDeclarationSyntax m:
                {
                    var member = new Member
                    {
                        Kind = Kind.Method,
                        Name = m.Identifier.Text,
                        ReturnType = Collapse(m.ReturnType.ToString()),
                        TypeParams = m.TypeParameterList?.Parameters.Select(p => p.Identifier.Text).ToList() ?? new(),
                        Params = Params(m.ParameterList),
                        Doc = ParseDoc(m),
                    };
                    member.Signature = Prefix($"{member.ReturnType} {member.Name}{Collapse(m.TypeParameterList?.ToString() ?? "")}{ParamText(m.ParameterList)}" +
                                              (m.ConstraintClauses.Count > 0 ? " " + Collapse(m.ConstraintClauses.ToString()) : "") + ";");
                    member.Title = member.Name + (member.TypeParams.Count > 0 ? "<" + string.Join(",", member.TypeParams) + ">" : "") + ParamTitle(member.Params);
                    return member;
                }
                case ConstructorDeclarationSyntax c:
                {
                    var member = new Member { Kind = Kind.Constructor, Name = typeName, Params = Params(c.ParameterList), Doc = ParseDoc(c) };
                    member.Signature = Prefix($"{typeName}{ParamText(c.ParameterList)};");
                    member.Title = typeName + ParamTitle(member.Params);
                    return member;
                }
                case PropertyDeclarationSyntax p:
                {
                    var member = new Member { Kind = Kind.Property, Name = p.Identifier.Text, ReturnType = Collapse(p.Type.ToString()), Doc = ParseDoc(p) };
                    member.Signature = Prefix($"{member.ReturnType} {member.Name} {Accessors(p.AccessorList, p.ExpressionBody is not null)}");
                    member.Title = member.Name;
                    return member;
                }
                case IndexerDeclarationSyntax ix:
                {
                    var member = new Member { Kind = Kind.Property, Name = "Item", ReturnType = Collapse(ix.Type.ToString()), Params = Params(ix.ParameterList), Doc = ParseDoc(ix) };
                    member.Signature = Prefix($"{member.ReturnType} this{Collapse(ix.ParameterList.ToString())} {Accessors(ix.AccessorList, ix.ExpressionBody is not null)}");
                    member.Title = "Item[" + string.Join(", ", member.Params.Select(x => ShortType(x.Type))) + "]";
                    return member;
                }
                case EventFieldDeclarationSyntax ef:
                {
                    var v = ef.Declaration.Variables.First();
                    var member = new Member { Kind = Kind.Event, Name = v.Identifier.Text, ReturnType = Collapse(ef.Declaration.Type.ToString()), Doc = ParseDoc(ef) };
                    member.Signature = Prefix($"event {member.ReturnType} {member.Name};");
                    member.Title = member.Name;
                    return member;
                }
                case EventDeclarationSyntax ev:
                {
                    var member = new Member { Kind = Kind.Event, Name = ev.Identifier.Text, ReturnType = Collapse(ev.Type.ToString()), Doc = ParseDoc(ev) };
                    member.Signature = Prefix($"event {member.ReturnType} {member.Name};");
                    member.Title = member.Name;
                    return member;
                }
                case FieldDeclarationSyntax f:
                {
                    var v = f.Declaration.Variables.First();
                    var member = new Member { Kind = Kind.Field, Name = v.Identifier.Text, ReturnType = Collapse(f.Declaration.Type.ToString()), Doc = ParseDoc(f) };
                    var isConst = f.Modifiers.Any(t => t.IsKind(SyntaxKind.ConstKeyword));
                    member.Signature = Prefix($"{member.ReturnType} {member.Name}" + (isConst && v.Initializer is not null ? " " + Collapse(v.Initializer.ToString()) : "") + ";");
                    member.Title = member.Name;
                    return member;
                }
                default:
                    return null;
            }
        }

        private static List<Param> Params(BaseParameterListSyntax list) => list.Parameters.Select(p => new Param
        {
            Name = p.Identifier.Text,
            Type = Collapse(p.Type?.ToString() ?? ""),
            Modifier = string.Join(" ", p.Modifiers.Select(t => t.Text)),
        }).ToList();

        private static string ParamText(BaseParameterListSyntax list) =>
            "(" + string.Join(", ", list.Parameters.Select(p => Collapse(p.WithAttributeLists(default).ToString()))) + ")";

        private static string ParamTitle(List<Param> ps) => "(" + string.Join(", ", ps.Select(p => ShortType(p.Type))) + ")";

        // The accessors a reader can call: a private or internal accessor is not part of the surface.
        private static string Accessors(AccessorListSyntax? list, bool expressionBodied)
        {
            if (list is null) return expressionBodied ? "{ get; }" : "{ get; }";
            var visible = list.Accessors
                .Where(a => !a.Modifiers.Any(t => t.IsKind(SyntaxKind.PrivateKeyword) || t.IsKind(SyntaxKind.InternalKeyword)))
                .Select(a => (a.Modifiers.Count > 0 ? string.Join(" ", a.Modifiers.Select(t => t.Text)) + " " : "") + a.Keyword.Text + ";");
            return "{ " + string.Join(" ", visible) + " }";
        }

        private static bool IsVisible(SyntaxTokenList mods) =>
            (mods.Any(t => t.IsKind(SyntaxKind.PublicKeyword)) || mods.Any(t => t.IsKind(SyntaxKind.ProtectedKeyword)))
            && !mods.Any(t => t.IsKind(SyntaxKind.PrivateKeyword));

        private static string GetNamespace(SyntaxNode node)
        {
            for (var p = node.Parent; p is not null; p = p.Parent)
                if (p is BaseNamespaceDeclarationSyntax ns) return ns.Name.ToString();
            return "";
        }

        private static int LineOf(SyntaxNode node)
        {
            // The line of the declaration itself, not of the doc comment above it.
            var token = node is MemberDeclarationSyntax m && m.Modifiers.Count > 0 ? m.Modifiers[0] : node.GetFirstToken();
            if (node is MemberDeclarationSyntax md && md.AttributeLists.Count > 0)
                token = md.Modifiers.Count > 0 ? md.Modifiers[0] : md.AttributeLists.Last().GetLastToken().GetNextToken();
            return token.GetLocation().GetLineSpan().StartLinePosition.Line + 1;
        }

        private static string Collapse(string s) => Regex.Replace(s, @"\s+", " ").Trim();

        // ------------------------------------------------------------------ XML docs

        private static DocumentationCommentTriviaSyntax? GetDocTrivia(SyntaxNode node) =>
            node.GetLeadingTrivia().Select(t => t.GetStructure()).OfType<DocumentationCommentTriviaSyntax>().FirstOrDefault();

        private static Doc ParseDoc(SyntaxNode node)
        {
            var doc = new Doc();
            var trivia = GetDocTrivia(node);
            if (trivia is null) return doc;

            var lines = trivia.ToFullString().Replace("\r\n", "\n").Split('\n')
                .Select(l => Regex.Replace(l, @"^\s*///\s?", ""));
            var root = ParseDocXml(string.Join("\n", lines));
            if (root is null) return doc;

            // Text written outside any tag (a comment with no <summary>) is what the author meant as
            // the summary; the part before the first tag is.
            doc.Summary = root.Element("summary") ?? LeadingText(root);
            doc.Remarks = root.Element("remarks");
            doc.Returns = root.Element("returns");
            doc.Value = root.Element("value");
            // Several <example> blocks are one Examples section.
            var examples = root.Elements("example").ToList();
            doc.Example = examples.Count <= 1 ? examples.FirstOrDefault() : new XElement("example", examples.SelectMany(e => e.Nodes()));
            foreach (var p in root.Elements("param"))
                if (p.Attribute("name") is { } n) doc.Params[n.Value] = p;
            foreach (var p in root.Elements("typeparam"))
                if (p.Attribute("name") is { } n) doc.TypeParams[n.Value] = p;
            foreach (var e in root.Elements("exception"))
                doc.Exceptions.Add((e.Attribute("cref")?.Value ?? "", e));
            return doc;
        }

        // A doc comment the compiler would warn about is still worth reading: an element left
        // unclosed (a missing </example>) is closed at the end of the comment, and a comment that
        // still does not parse yields whatever top-level elements parse on their own.
        private static XElement? ParseDocXml(string xml)
        {
            static XElement? TryParse(string text)
            {
                try { return XElement.Parse("<doc>" + text + "</doc>", LoadOptions.PreserveWhitespace); }
                catch (System.Xml.XmlException) { return null; }
            }

            if (TryParse(xml) is { } parsed) return parsed;

            var open = new Stack<string>();
            foreach (Match m in Regex.Matches(xml, @"<(/?)([A-Za-z]+)\b[^>]*?(/?)>"))
            {
                if (m.Groups[3].Value == "/") continue;
                var name = m.Groups[2].Value;
                if (m.Groups[1].Value == "") open.Push(name);
                else if (open.Contains(name)) { while (open.Count > 0 && open.Pop() != name) { } }
            }
            var closed = xml + string.Concat(open.Select(n => $"</{n}>"));
            if (TryParse(closed) is { } repaired) return repaired;

            var root = new XElement("doc");
            foreach (Match m in Regex.Matches(xml, @"<(summary|remarks|returns|value|example|param|typeparam|exception)\b[^>]*>[\s\S]*?</\1>"))
                if (TryParse(m.Value) is { } part) root.Add(part.Elements());
            return root.HasElements ? root : null;
        }

        private static XElement? LeadingText(XElement root)
        {
            var nodes = root.Nodes().TakeWhile(n => n is XText).ToList();
            return nodes.Count > 0 && nodes.Any(n => ((XText)n).Value.Trim().Length > 0) ? new XElement("summary", nodes) : null;
        }

        // Renders a doc element's content as Markdown. `from` is the page the text lands on,
        // so <see cref> links are made relative to it.
        private static string DocMarkdown(Context ctx, string from, XElement? el, bool inline = false)
        {
            if (el is null) return "";
            var sb = new StringBuilder();
            foreach (var node in el.Nodes()) AppendNode(ctx, from, node, sb);
            var text = sb.ToString();

            // Code blocks keep their line breaks and indentation: set them aside while the
            // prose around them is reflowed, then put them back.
            var blocks = new List<string>();
            text = Regex.Replace(text, @"```csharp\n[\s\S]*?\n```", m => { blocks.Add(m.Value); return $"\u0000{blocks.Count - 1}\u0000"; });
            if (inline)
                return Regex.Replace(Regex.Replace(text, @"\u0000\d+\u0000", ""), @"\s+", " ").Trim();

            text = Regex.Replace(text, @"[ \t]*\n[ \t]*(?!\n)", "\n");
            text = Regex.Replace(text, @"(?<!\n)\n(?!\n|- )", " ");
            text = Regex.Replace(text, @"[ ]{2,}", " ");
            text = Regex.Replace(text, @"\n{3,}", "\n\n").Trim();
            return Regex.Replace(text, @"\u0000(\d+)\u0000", m => blocks[int.Parse(m.Groups[1].Value)]);
        }

        private static void AppendNode(Context ctx, string from, XNode node, StringBuilder sb)
        {
            switch (node)
            {
                case XText t:
                    sb.Append(t.Value.Replace("<", "&lt;").Replace(">", "&gt;"));
                    break;
                case XElement e:
                    switch (e.Name.LocalName)
                    {
                        case "see":
                        case "seealso":
                            if (e.Attribute("langword") is { } lw) { sb.Append('`').Append(lw.Value).Append('`'); break; }
                            if (e.Attribute("href") is { } href) { sb.Append('[').Append(e.Value.Length > 0 ? e.Value : href.Value).Append("](").Append(href.Value).Append(')'); break; }
                            sb.Append(CrefMarkdown(ctx, from, e.Attribute("cref")?.Value ?? "", e.Value));
                            break;
                        case "paramref":
                        case "typeparamref":
                            sb.Append('`').Append(e.Attribute("name")?.Value).Append('`');
                            break;
                        case "c":
                            sb.Append('`').Append(e.Value).Append('`');
                            break;
                        case "code":
                            sb.Append("\n\n```csharp\n").Append(Dedent(e.Value)).Append("\n```\n\n");
                            break;
                        case "para":
                            sb.Append("\n\n");
                            foreach (var n in e.Nodes()) AppendNode(ctx, from, n, sb);
                            sb.Append("\n\n");
                            break;
                        case "br":
                            sb.Append("\n\n");
                            break;
                        case "list":
                            sb.Append("\n\n");
                            foreach (var item in e.Elements("item"))
                            {
                                var term = item.Element("term");
                                var desc = item.Element("description") ?? item;
                                sb.Append("- ");
                                if (term is not null) sb.Append("**").Append(DocMarkdown(ctx, from, term, true)).Append("**: ");
                                sb.Append(DocMarkdown(ctx, from, desc, true)).Append('\n');
                            }
                            sb.Append('\n');
                            break;
                        default:
                            foreach (var n in e.Nodes()) AppendNode(ctx, from, n, sb);
                            break;
                    }
                    break;
            }
        }

        private static string Dedent(string code)
        {
            var lines = code.Replace("\r\n", "\n").Split('\n').ToList();
            while (lines.Count > 0 && string.IsNullOrWhiteSpace(lines[0])) lines.RemoveAt(0);
            while (lines.Count > 0 && string.IsNullOrWhiteSpace(lines[^1])) lines.RemoveAt(lines.Count - 1);
            var indent = lines.Where(l => l.Trim().Length > 0).Select(l => l.Length - l.TrimStart().Length).DefaultIfEmpty(0).Min();
            return string.Join("\n", lines.Select(l => l.Length >= indent ? l.Substring(indent) : l.TrimStart()));
        }

        // T:Ns.Type, M:Ns.Type.Member(args), Type.Member, Member → a link when the target is
        // documented in this run or is a known BCL type; code text otherwise.
        private static string CrefMarkdown(Context ctx, string from, string cref, string text)
        {
            var c = Regex.Replace(cref, @"^[A-Z]:", "");
            c = Regex.Replace(c, @"\(.*\)$", "");
            c = Regex.Replace(c, @"`\d+", "").Replace('{', '<').Replace('}', '>');
            var segments = c.Split('.');
            var last = Regex.Replace(segments[^1], "<.*>", "");
            var display = text.Length > 0 ? text : segments[^1];

            for (var i = segments.Length - 1; i >= 1; i--)
            {
                var key = Regex.Replace(segments[i - 1], "<.*>", "") + "." + last;
                if (ctx.MemberPages.TryGetValue(key, out var mp)) return $"[{Esc(display)}]({RelLink(ctx, from, mp)})";
            }
            // A bare member name (cref="Render(string)") means a member of the type being documented.
            if (segments.Length == 1 && ctx.MemberPages.TryGetValue($"{ctx.CurrentType}.{last}", out var own))
                return $"[{Esc(display)}]({RelLink(ctx, from, own)})";
            if (ctx.TypePages.TryGetValue(last, out var tp)) return $"[{Esc(display)}]({RelLink(ctx, from, tp)})";
            if (segments.Length == 1 && Bcl.TryGetValue(last, out var slug)) return $"[{Esc(display)}](https://learn.microsoft.com/dotnet/api/{slug})";
            return "`" + display + "`";
        }

        // ------------------------------------------------------------------ type rendering

        /// <summary>A type name as Learn titles show it: keyword aliases spelled as CLR names, no nullable marks.</summary>
        private static string ShortType(string type)
        {
            var t = Regex.Replace(type, @"\b(" + string.Join("|", Keywords.Keys) + @")\b", m => Keywords[m.Value]);
            return t.Replace("?", "").Replace(" ", "").Replace(",", ", ");
        }

        // A type with each known identifier linked, as HTML (it lands inside raw HTML lines).
        private static string TypeHtml(Context ctx, string from, string type)
        {
            var t = ShortType(type);
            var sb = new StringBuilder();
            foreach (Match m in Regex.Matches(t, @"[A-Za-z_][\w.]*|[^A-Za-z_]+"))
            {
                var token = m.Value;
                if (!char.IsLetter(token[0]) && token[0] != '_') { sb.Append(WebUtility.HtmlEncode(token)); continue; }
                var simple = token.Split('.')[^1];
                if (ctx.TypePages.TryGetValue(simple, out var page))
                    sb.Append($"<a href=\"{RelLink(ctx, from, page)}\">{simple}</a>");
                else if (Bcl.TryGetValue(simple, out var slug))
                    sb.Append($"<a href=\"https://learn.microsoft.com/dotnet/api/{slug}\">{simple}</a>");
                else
                    sb.Append(WebUtility.HtmlEncode(simple));
            }
            return sb.ToString();
        }

        // ------------------------------------------------------------------ links & paths

        // Root-relative and extensionless, like the site's own links. Source roots come only from the
        // root neko.yml, so the sync always runs at the site root and these paths are its URLs. A relative
        // link would break on a folder page opened without its trailing slash.
        private static string RelLink(Context ctx, string from, string to)
        {
            var stem = Path.GetFileNameWithoutExtension(to);
            var dir = Path.GetRelativePath(ctx.InputDir, Path.GetDirectoryName(to)!).Replace('\\', '/');
            dir = dir == "." ? "" : dir + "/";
            return "/" + (IsFolderIndex(stem) ? dir : dir + stem);
        }

        private static string Kebab(string name) => Regex.Replace(name, @"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "-").ToLowerInvariant();

        private static string Esc(string s) => s.Replace("<", "&lt;").Replace(">", "&gt;");

        private static string Cell(string s) => Regex.Replace(s, @"\s+", " ").Replace("|", "\\|").Trim() is { Length: > 0 } c ? c : "&nbsp;";

