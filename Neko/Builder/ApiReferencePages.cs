        private static void WritePage(Context ctx, Page page, ApiDocsSync.Result result, bool verbose, bool dryRun)
        {
            var model = page.Model!;
            ctx.CurrentType = model.Name;
            var rel = Path.GetRelativePath(ctx.InputDir, page.Path);
            var text = File.ReadAllText(page.Path);

            var typeAttrs = AttrString(page.Attrs);
            var newText = TypeMarker.Replace(text, m =>
                ApiDocsSync.InsideFence(text, m.Index) ? m.Value
                    : $"<!-- api:type start {typeAttrs} -->\n\n{RenderTypeHeader(ctx, page).TrimEnd('\n')}\n\n<!-- api:type end -->", 1);
            newText = MembersMarker.Replace(newText, m =>
            {
                if (ApiDocsSync.InsideFence(newText, m.Index)) return m.Value;
                var own = ApiDocsSync.ParseAttrs(m.Groups["attrs"].Value);
                var attrs = new Dictionary<string, string>(page.Attrs, StringComparer.OrdinalIgnoreCase);
                foreach (var kv in own) attrs[kv.Key] = kv.Value;
                var head = own.Count > 0 ? $"<!-- api:members start {AttrString(own)} -->" : "<!-- api:members start -->";
                return $"{head}\n\n{RenderMemberTables(ctx, page, attrs).TrimEnd('\n')}\n\n<!-- api:members end -->";
            }, 1);

            var written = new HashSet<string>(StringComparer.Ordinal);
            var outputs = new List<(string Path, string Content)>();

            foreach (var group in model.Members.GroupBy(m => (m.Kind, m.Name)))
            {
                var path = MemberPagePath(page, group.Key.Kind, group.Key.Name);
                outputs.Add((path, RenderMemberPage(ctx, page, path, group.ToList())));
            }

            if (!dryRun)
            {
                if (newText != text) File.WriteAllText(page.Path, newText);
                foreach (var (kind, title, folder, order) in Sections)
                {
                    if (kind == Kind.Constructor || !model.Members.Any(m => m.Kind == kind)) continue;
                    var dir = Path.Combine(page.OutputDir, folder);
                    Directory.CreateDirectory(dir);
                    var yml = Path.Combine(dir, "index.yml");
                    if (!File.Exists(yml)) File.WriteAllText(yml, $"label: \"{title}\"\norder: {order}\nexpanded: false\n");
                }
            }

            var changed = newText != text ? 1 : 0;
            foreach (var (path, content) in outputs)
            {
                written.Add(Path.GetFullPath(path));
                if (File.Exists(path) && File.ReadAllText(path) == content) continue;
                changed++;
                if (!dryRun) File.WriteAllText(path, content);
            }

            // Pages this type generated before and no longer produces (a member was removed or renamed).
            var candidates = Sections.Where(s => s.Kind != Kind.Constructor)
                .Select(s => Path.Combine(page.OutputDir, s.Folder))
                .Where(Directory.Exists)
                .SelectMany(d => Directory.EnumerateFiles(d, "*.md"))
                .Append(Path.Combine(page.OutputDir, "constructors.md"))
                .Where(File.Exists);
            foreach (var stale in candidates.Where(p => !written.Contains(Path.GetFullPath(p))).ToList())
            {
                if (!File.ReadAllText(stale).Contains(GeneratedNotice)) continue;
                changed++;
                if (!dryRun) File.Delete(stale);
                if (verbose) Console.WriteLine($"  api-docs: {(dryRun ? "would remove" : "removed")} {Path.GetRelativePath(ctx.InputDir, stale)}");
            }

            result.MarkerRefreshes++;
            result.PagesGenerated += outputs.Count;
            if (changed > 0) result.FilesUpdated += changed;
            Console.WriteLine($"  api-docs: {model.Name}: {model.Members.Count} member(s) on {outputs.Count} page(s) → {rel}");
        }

        private static string AttrString(Dictionary<string, string> attrs) =>
            string.Join(" ", attrs.OrderBy(kv => Array.IndexOf(AttrOrder, kv.Key.ToLowerInvariant()) is var i && i < 0 ? 99 : i)
                .Select(kv => $"{kv.Key}=\"{kv.Value}\""));

        // A root-relative or absolute link is kept; a relative one is written from the type page and is
        // re-based onto the page being rendered.
        // A root-relative or absolute link is kept; a relative one is read from the type page.
        private static string NamespaceHref(Context ctx, Page page, string from, string link)
        {
            if (link.StartsWith("/") || link.Contains("://")) return link;
            var target = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(page.Path)!, link));
            var rel = Path.GetRelativePath(ctx.InputDir, target).Replace('\\', '/').TrimEnd('/');
            return "/" + (rel == "." ? "" : rel + (link.EndsWith("/") ? "/" : ""));
        }

        private static string Definition(Context ctx, Page page, string from, string? sourceFile, int line, bool withSource = true)
        {
            var a = page.Attrs;
            var sb = new StringBuilder();
            sb.Append("## Definition\n\n:::api-ref-def { .not-prose }\n\n");
            if (page.Model!.Namespace.Length > 0)
            {
                var ns = WebUtility.HtmlEncode(page.Model.Namespace);
                // namespaceLink: the namespace's own page, written as a link from the type page.
                if (a.TryGetValue("namespaceLink", out var nsLink) && nsLink.Length > 0)
                    ns = $"<a href=\"{NamespaceHref(ctx, page, from, nsLink)}\">{ns}</a>";
                sb.Append($"<p><span>Namespace:</span> {ns}</p>\n");
            }
            if (a.TryGetValue("assembly", out var asm)) sb.Append($"<p><span>Assembly:</span> {WebUtility.HtmlEncode(asm)}</p>\n");
            if (a.TryGetValue("package", out var pkg))
            {
                a.TryGetValue("version", out var ver);
                sb.Append($"<p><span>Package:</span> <a href=\"https://www.nuget.org/packages/{pkg}{(string.IsNullOrEmpty(ver) ? "" : "/" + ver)}\">{WebUtility.HtmlEncode(pkg)}</a>{(string.IsNullOrEmpty(ver) ? "" : " v" + WebUtility.HtmlEncode(ver))}</p>\n");
            }
            if (withSource && sourceFile is not null) sb.Append(SourceLine(page, sourceFile, line));
            sb.Append("\n:::\n");
            return sb.ToString();
        }

        private static string SourceLine(Page page, string sourceFile, int line)
        {
            var file = Path.GetFileName(sourceFile);
            return page.Attrs.TryGetValue("source", out var baseUrl) && baseUrl.Length > 0
                ? $"<p><span>Source:</span> <a href=\"{baseUrl.TrimEnd('/')}/{sourceFile}#L{line}\">{WebUtility.HtmlEncode(file)}</a></p>\n"
                : $"<p><span>Source:</span> {WebUtility.HtmlEncode(file)}</p>\n";
        }

        private static string Code(string code) => $"```csharp title=\"C#\"\n{code}\n```\n";

        private static string RenderTypeHeader(Context ctx, Page page)
        {
            var model = page.Model!;
            var from = page.Path;
            var sb = new StringBuilder();
            sb.Append("<div class=\"api-ref-page\"></div>\n\n");
            sb.Append(Definition(ctx, page, from, model.SourceFile, model.Line)).Append('\n');
            var summary = DocMarkdown(ctx, from, model.Doc.Summary);
            if (summary.Length > 0) sb.Append(summary).Append("\n\n");
            sb.Append(Code(model.Declaration)).Append('\n');

            if (model.TypeParams.Count > 0)
                sb.Append(InfoBlock("Type Parameters", model.TypeParams.Select(tp =>
                    ($"<code class=\"api-ref-name\">{tp}</code>", DocMarkdown(ctx, from, model.Doc.TypeParams.GetValueOrDefault(tp))))));

            var interfaces = model.Bases.Where(LooksLikeInterface).ToList();
            var baseClass = model.Kind is "class" or "record" ? model.Bases.FirstOrDefault(b => !LooksLikeInterface(b)) : null;
            var chain = model.Kind switch
            {
                "interface" => new List<string>(),
                "struct" or "record struct" => new List<string> { "Object", "ValueType" },
                "enum" => new List<string> { "Object", "ValueType", "Enum" },
                _ => baseClass is null ? new List<string> { "Object" } : new List<string> { "Object", baseClass },
            };

            if (chain.Count > 0 || interfaces.Count > 0)
            {
                sb.Append(":::api-ref-attrs { .not-prose }\n\n");
                if (chain.Count > 0)
                    sb.Append("<p><span>Inheritance</span> ")
                      .Append(string.Join(" <span class=\"api-ref-arrow\">→</span> ", chain.Select(c => TypeHtml(ctx, from, c)).Append(WebUtility.HtmlEncode(model.Name))))
                      .Append("</p>\n");
                if (interfaces.Count > 0)
                    sb.Append("<p><span>Implements</span> ").Append(string.Join(", ", interfaces.Select(i => TypeHtml(ctx, from, i)))).Append("</p>\n");
                sb.Append("\n:::\n\n");
            }

            if (model.Doc.Example is not null) sb.Append("## Examples\n\n").Append(DocMarkdown(ctx, from, model.Doc.Example)).Append("\n\n");
            if (model.Doc.Remarks is not null) sb.Append("## Remarks\n\n").Append(DocMarkdown(ctx, from, model.Doc.Remarks)).Append("\n\n");
            return sb.ToString();
        }

        // Interfaces follow the I-prefix convention; without a semantic model it is the only signal there is.
        private static bool LooksLikeInterface(string name) => Regex.IsMatch(name.Split('.')[^1], @"^I[A-Z]");

        private static string RenderMemberTables(Context ctx, Page page, Dictionary<string, string> attrs)
        {
            var model = page.Model!;
            var from = page.Path;
            var sb = new StringBuilder();

            if (model.Kind == "enum")
            {
                sb.Append("## Fields\n\n:::api-ref-table { .not-prose }\n\n| Name | Value | Description |\n| --- | --- | --- |\n");
                foreach (var (name, value, doc) in model.EnumValues)
                    sb.Append($"| {name} | {Cell(value)} | {Cell(DocMarkdown(ctx, from, doc.Summary, true))} |\n");
                sb.Append("\n:::\n\n");
            }

            foreach (var (kind, title, _, _) in Sections)
            {
                var members = model.Members.Where(m => m.Kind == kind).ToList();
                var rows = new List<(string Sort, string Name, string Desc)>();
                foreach (var group in members.GroupBy(m => m.Name))
                {
                    var path = MemberPagePath(page, kind, group.Key);
                    var link = RelLink(ctx, from, path);
                    var many = group.Count() > 1;
                    foreach (var m in group)
                        rows.Add((m.Title, $"[{Wbr(Esc(m.Title))}]({link}{(many ? "#" + m.Anchor : "")})", DocMarkdown(ctx, from, m.Doc.Summary, true)));
                }

                var inherit = kind == Kind.Method && model.Kind is "class" or "record" && !model.IsStatic &&
                              !(attrs.TryGetValue("inherited", out var inh) && inh.Equals("false", StringComparison.OrdinalIgnoreCase));
                if (inherit)
                    foreach (var (otitle, oname, slug, summary) in ObjectMembers)
                        if (!members.Any(m => m.Name == oname))
                            rows.Add((otitle, $"[{Wbr(otitle)}](https://learn.microsoft.com/dotnet/api/{slug})",
                                summary + "<br>(Inherited from [Object](https://learn.microsoft.com/dotnet/api/system.object))"));

                if (rows.Count == 0) continue;
                sb.Append($"## {title}\n\n:::api-ref-table {{ .not-prose }}\n\n| Name | Description |\n| --- | --- |\n");
                foreach (var row in rows.OrderBy(r => r.Sort, StringComparer.OrdinalIgnoreCase))
                    sb.Append($"| {row.Name} | {Cell(row.Desc)} |\n");
                sb.Append("\n:::\n\n");
            }

            sb.Append(AppliesTo(attrs, "##"));
            return sb.ToString();
        }

        // Lets a long PascalCase name wrap at its word boundaries in a narrow table column.
        private static string Wbr(string s) => Regex.Replace(s, @"(?<=[a-z])(?=[A-Z])", "<wbr>");

        // A section inside one overload is a label, not a heading, so "On this page" lists only the
        // overloads themselves, as Learn's "In this article" does.
        private static string SubHeading(string level, string title) =>
            level == "##" ? $"## {title}\n\n" : $"<p class=\"api-ref-info\">{title}</p>\n\n";

        private static string AppliesTo(Dictionary<string, string> attrs, string heading)
        {
            if (!attrs.TryGetValue("package", out var pkg) || !attrs.TryGetValue("version", out var ver)) return "";
            return $"{SubHeading(heading, "Applies to")}:::api-ref-applies {{ .not-prose }}\n\n| Product | Versions |\n| --- | --- |\n| **{pkg}** | {ver} |\n\n:::\n\n";
        }

        private static string InfoBlock(string title, IEnumerable<(string Head, string Desc)> rows)
        {
            var sb = new StringBuilder();
            sb.Append($"<p class=\"api-ref-info\">{title}</p>\n\n");
            foreach (var (head, desc) in rows)
            {
                sb.Append($"<p class=\"api-ref-param\">{head}</p>\n\n");
                if (desc.Length > 0) sb.Append(desc).Append("\n\n");
            }
            return sb.ToString();
        }

        private static string RenderMemberPage(Context ctx, Page page, string path, List<Member> group)
        {
            var model = page.Model!;
            var first = group[0];
            var kindTitle = first.Kind switch
            {
                Kind.Constructor => group.Count > 1 ? "Constructors" : "Constructor",
                Kind.Property => "Property",
                Kind.Event => "Event",
                Kind.Field => "Field",
                _ => "Method",
            };

            var label = first.Kind == Kind.Constructor ? "Constructors" : first.Name;
            var h1 = first.Kind switch
            {
                Kind.Constructor => group.Count > 1 ? $"{model.Name} Constructors" : $"{Esc(first.Title)} Constructor",
                Kind.Method when group.Count == 1 => $"{model.Name}.{Esc(first.Title)} Method",
                _ => $"{model.Name}.{first.Name} {kindTitle}",
            };

            var sb = new StringBuilder();
            sb.Append("---\n").Append($"label: \"{label}\"\n");
            if (first.Kind == Kind.Constructor) sb.Append("order: 5\n");
            sb.Append("---\n\n");
            sb.Append(GeneratedNotice).Append("\n\n<div class=\"api-ref-page\"></div>\n\n");
            sb.Append($"# {h1}\n\n");

            if (group.Count == 1)
            {
                sb.Append(Definition(ctx, page, path, first.SourceFile, first.Line)).Append('\n');
                sb.Append(MemberBody(ctx, path, first, "##"));
                sb.Append(AppliesTo(page.Attrs, "##"));
            }
            else
            {
                sb.Append(Definition(ctx, page, path, null, 0, withSource: false)).Append('\n');
                var shared = DocMarkdown(ctx, path, first.Doc.Summary);
                if (shared.Length > 0) sb.Append(shared).Append("\n\n");
                sb.Append("## Overloads\n\n:::api-ref-table { .not-prose }\n\n| Name | Description |\n| --- | --- |\n");
                foreach (var m in group)
                    sb.Append($"| [{Wbr(Esc(m.Title))}](#{m.Anchor}) | {Cell(DocMarkdown(ctx, path, m.Doc.Summary, true))} |\n");
                sb.Append("\n:::\n\n");
                foreach (var m in group)
                {
                    sb.Append($"## {Esc(m.Title)} {{#{m.Anchor}}}\n\n::::api-ref-member\n\n");
                    sb.Append(":::api-ref-def { .not-prose }\n\n").Append(SourceLine(page, m.SourceFile, m.Line)).Append("\n:::\n\n");
                    sb.Append(MemberBody(ctx, path, m, "###"));
                    sb.Append(AppliesTo(page.Attrs, "###"));
                    sb.Append("::::\n\n");
                }
            }
            return sb.ToString().TrimEnd('\n') + "\n";
        }

        private static string MemberBody(Context ctx, string from, Member m, string sub)
        {
            var d = m.Doc;
            var sb = new StringBuilder();
            var summary = DocMarkdown(ctx, from, d.Summary);
            if (summary.Length > 0) sb.Append(summary).Append("\n\n");
            sb.Append(Code(m.Signature)).Append('\n');

            if (m.TypeParams.Count > 0)
                sb.Append(InfoBlock("Type Parameters", m.TypeParams.Select(tp =>
                    ($"<code class=\"api-ref-name\">{tp}</code>", DocMarkdown(ctx, from, d.TypeParams.GetValueOrDefault(tp))))));
            if (m.Params.Count > 0)
                sb.Append(InfoBlock("Parameters", m.Params.Select(p =>
                    ($"<code class=\"api-ref-name\">{p.Name}</code> <span class=\"api-ref-type\">{TypeHtml(ctx, from, p.Type)}</span>",
                     DocMarkdown(ctx, from, d.Params.GetValueOrDefault(p.Name))))));

            switch (m.Kind)
            {
                case Kind.Method when m.ReturnType != "void":
                    sb.Append(InfoBlock("Returns", new[] { ($"<span class=\"api-ref-type\">{TypeHtml(ctx, from, m.ReturnType)}</span>", DocMarkdown(ctx, from, d.Returns)) }));
                    break;
                case Kind.Property:
                    sb.Append(InfoBlock("Property Value", new[] { ($"<span class=\"api-ref-type\">{TypeHtml(ctx, from, m.ReturnType)}</span>", DocMarkdown(ctx, from, d.Value ?? d.Returns)) }));
                    break;
                case Kind.Event:
                    sb.Append(InfoBlock("Event Type", new[] { ($"<span class=\"api-ref-type\">{TypeHtml(ctx, from, m.ReturnType)}</span>", "") }));
                    break;
                case Kind.Field:
                    sb.Append(InfoBlock("Field Value", new[] { ($"<span class=\"api-ref-type\">{TypeHtml(ctx, from, m.ReturnType)}</span>", "") }));
                    break;
            }

