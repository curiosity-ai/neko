    /// <summary>
    /// Generates a Microsoft Learn-style API reference for one type: a definition block and
    /// member tables on the type's own page, and one page per member group (methods, properties,
    /// events, fields, constructors) next to it. A type page carries two marker pairs:
    /// <code>
    /// &lt;!-- api:type start repo="mosaik" file="src/Graph.cs" type="Graph" --&gt;
    /// &lt;!-- api:type end --&gt;
    ///   …hand-written Examples / Remarks…
    /// &lt;!-- api:members start --&gt;
    /// &lt;!-- api:members end --&gt;
    /// </code>
    /// Both blocks, and every member page, are regenerated on each run. Member pages carry
    /// <see cref="GeneratedNotice"/>; a page with the notice that the type no longer produces is
    /// deleted, a page without it is never touched. Like <c>api:source</c>, only the public
    /// surface is read and a marker whose source root is missing is left as it is.
    /// </summary>
    public static class ApiReferencePages
    {
        public const string GeneratedNotice = "<!-- generated by neko sync-api-docs from the source's XML doc comments: edit those, not this page -->";

        private static readonly Regex TypeMarker = new(
            @"<!--\s*api:type\s+start\s+(?<attrs>.*?)-->(?<body>[\s\S]*?)<!--\s*api:type\s+end\s*-->",
            RegexOptions.Compiled);

        private static readonly Regex MembersMarker = new(
            @"<!--\s*api:members\s+start(?<attrs>.*?)-->(?<body>[\s\S]*?)<!--\s*api:members\s+end\s*-->",
            RegexOptions.Compiled);

        private static readonly string[] AttrOrder = { "repo", "file", "type", "namespacelink", "assembly", "package", "version", "source", "inherited" };

